export function readLanguage(): Language {
  try {
    return localStorage.getItem(LANGUAGE_KEY) === "en" ? "en" : "ar";
  } catch {
    return "ar";
  }
}

export function saveLanguage(language: Language) {
  localStorage.setItem(LANGUAGE_KEY, language);
  window.dispatchEvent(new CustomEvent("taskflow:language", { detail: language }));
}

export function useLanguage() {
  const [language, setLanguage] = useState<Language>(readLanguage);
  useEffect(() => {
    const onLanguage = (event: Event) => setLanguage((event as CustomEvent<Language>).detail);
    window.addEventListener("taskflow:language", onLanguage);
    return () => window.removeEventListener("taskflow:language", onLanguage);
  }, []);
  return language;
}

